    static Map<String, List<DiaryTask>> tasks()
    {
        Map<String, List<DiaryTask>> copy = new LinkedHashMap<>();
        TASKS.forEach((id, tasks) -> copy.put(id, Collections.unmodifiableList(tasks)));
        return Collections.unmodifiableMap(copy);
    }
    static Map<String, List<Requirement>> rules()
    {
        Map<String, List<Requirement>> copy = new LinkedHashMap<>();
        TASKS.forEach((id, tasks) -> {
            List<Requirement> rules = new ArrayList<>();
            tasks.forEach(task -> rules.addAll(task.requirements));
            copy.put(id, Collections.unmodifiableList(rules));
        });
        return Collections.unmodifiableMap(copy);
    }
    private static void add(String id, DiaryTask task)
    {
        TASKS.computeIfAbsent(id, ignored -> new ArrayList<>()).add(task);
    }
